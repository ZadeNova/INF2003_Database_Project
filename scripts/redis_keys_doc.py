"""Regenerate the "Redis keys" table in docs/DATA_MODEL.md from src/config/redis_keys.py (pure data, no Redis needed).

python scripts/redis_keys_doc.py            # rewrite the table between the generated-section markers
python scripts/redis_keys_doc.py --check    # exit 1 if the document differs from the registry
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from config import redis_keys  # noqa: E402

DOCUMENT = ROOT / "docs" / "DATA_MODEL.md"
START = "<!-- generated by scripts/redis_keys_doc.py -->"
END = "<!-- end generated -->"


def section():
    return f"{START}\n{redis_keys.render_table()}\n{END}"


def current(text):
    """The generated section as it stands in the document, markers included."""
    begin = text.index(START)
    return text[begin : text.index(END, begin) + len(END)]


def updated(text):
    return text.replace(current(text), section())


def main(argv):
    text = DOCUMENT.read_text(encoding="utf-8")
    if "--check" in argv:
        if current(text) != section():
            print("docs/DATA_MODEL.md is out of date: run python scripts/redis_keys_doc.py")
            return 1
        return 0
    DOCUMENT.write_text(updated(text), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
