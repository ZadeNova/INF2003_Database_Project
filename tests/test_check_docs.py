"""Each rule of scripts/check_docs.py catches its case and leaves a clean tree alone."""

import importlib.util
import shutil
import subprocess
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parent.parent / "scripts" / "check_docs.py"
spec = importlib.util.spec_from_file_location("check_docs", SCRIPT)
check_docs = importlib.util.module_from_spec(spec)
spec.loader.exec_module(check_docs)

COMPOSE = "name: t\nservices:\n  db:\n    image: x\n  web:\n    image: y\n"


@pytest.fixture
def repo(tmp_path):
    def write(name, text=""):
        path = tmp_path / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")

    write("README.md", "# Title\n")
    write("compose.yaml", COMPOSE)
    write("scripts/run.py", "")
    write("src/app.py", "")
    write.root = tmp_path
    return write


def problems(repo):
    return check_docs.check(repo.root)


def test_a_clean_tree_passes(repo):
    repo("README.md", "# T\n[a](docs/DECISIONS.md) and `src/app.py` and `<placeholder>/x`\n")
    repo("docs/DECISIONS.md", "[back](../README.md#top)\n")
    assert problems(repo) == []


def test_broken_relative_link(repo):
    repo("README.md", "[gone](docs/missing.md) [ok](https://example.com) [anchor](#top)\n")
    (error,) = problems(repo)
    assert "broken link to docs/missing.md" in error


def test_links_inside_code_are_not_links(repo):
    repo("README.md", "`[x](nowhere.md)`\n\n```\n[x](nowhere.md)\n```\n")
    assert problems(repo) == []


def test_backticked_repository_path_that_does_not_exist(repo):
    repo(
        "README.md",
        "See `src/missing.py` and `src/app.py`, glob `src/*.py`, placeholder `src/<name>.py`, "
        "container path `/app/tests`.\n",
    )
    (error,) = problems(repo)
    assert "`src/missing.py` does not exist" in error


def test_path_rule_skips_plan_files(repo):
    repo("PLAN.md", "Future: `src/not_yet.py`\n")
    repo("docs/plans/x.md", "status: draft\nFuture: `scripts/not_yet.py`\n")
    assert problems(repo) == []


def test_markdown_file_outside_the_list(repo):
    repo("notes/extra.md", "# extra\n")
    repo("src/static/vendor/lib/README.md", "vendored\n")
    repo("docs/plans/ok.md", "status: draft\n")
    (error,) = problems(repo)
    assert error.startswith("notes/extra.md") and "documentation list" in error


@pytest.mark.parametrize(
    "text, expected",
    [
        ("<!-- generated by scripts/run.py -->\nx\n<!-- end generated -->\n", None),
        ("<!-- generated by scripts/run.py -->\nx\n", "never closed"),
        ("x\n<!-- end generated -->\n", "without a start marker"),
        ("<!-- generated by scripts/gone.py -->\nx\n<!-- end generated -->\n", "scripts/gone.py, which does not exist"),
        ("`<!-- generated by scripts/gone.py -->` quoted\n", None),
    ],
)
def test_generated_section_markers(repo, text, expected):
    repo("README.md", text)
    found = problems(repo)
    if expected is None:
        assert found == []
    else:
        (error,) = found
        assert expected in error


def test_plan_needs_a_valid_status(repo):
    repo("docs/plans/finished.md", "# done\n\nstatus: done\n")
    repo("docs/plans/going.md", "# going\n\nstatus: in-progress\n")
    repo("docs/plans/odd.md", "# odd\n\nstatus: shipped\n")
    (error,) = problems(repo)
    assert error.startswith("docs/plans/odd.md") and "status line" in error


def test_readme_commands_name_existing_scripts_and_services(repo):
    repo(
        "README.md",
        "```sh\npython scripts/run.py\npython scripts/gone.py\n"
        "docker compose run --rm -e A=b web pytest\ndocker compose run --rm ghost ls\n"
        "docker compose up --build\n```\n",
    )
    errors = problems(repo)
    assert len(errors) == 2
    assert any("scripts/gone.py" in error for error in errors)
    assert any("service ghost" in error for error in errors)


def test_main_reports_a_nonzero_status(repo, capsys):
    repo("README.md", "[gone](missing.md)\n")
    assert check_docs.main(["check_docs.py", str(repo.root)]) == 1
    assert "broken link" in capsys.readouterr().err


needs_git = pytest.mark.skipif(shutil.which("git") is None, reason="the staged check reads the git index")


def git(repo, *args):
    subprocess.run(["git", *args], cwd=repo.root, check=True, capture_output=True)


@needs_git
def test_staged_check_reads_the_index_not_the_working_tree(repo):
    git(repo, "init", "-q")
    repo("README.md", "[gone](missing.md)\n")
    git(repo, "add", "-A")
    repo("README.md", "# fixed on disk only\n")

    assert problems(repo) == []
    (error,) = check_docs.check(repo.root, staged=True)
    assert "README.md:1: broken link to missing.md" in error


@needs_git
def test_staged_check_does_not_count_files_that_are_not_staged(repo):
    git(repo, "init", "-q")
    git(repo, "add", "-A")
    repo("src/new.py", "# not staged\n")
    repo("README.md", "[n](src/new.py) `src/new.py`\n")
    git(repo, "add", "README.md")

    assert problems(repo) == []
    errors = check_docs.check(repo.root, staged=True)
    assert len(errors) == 2 and all("src/new.py" in error for error in errors)


@needs_git
def test_staged_check_resolves_relative_links_and_directories(repo):
    git(repo, "init", "-q")
    repo("docs/DECISIONS.md", "[up](../README.md) [dir](../src/) [out](../../etc/passwd)\n")
    repo("README.md", "# T\n[self](docs/DECISIONS.md#x)\n")
    git(repo, "add", "-A")

    (error,) = check_docs.check(repo.root, staged=True)
    assert "broken link to ../../etc/passwd" in error


@needs_git
def test_main_accepts_staged_flag(repo, capsys):
    git(repo, "init", "-q")
    repo("README.md", "[gone](missing.md)\n")
    git(repo, "add", "-A")
    assert check_docs.main(["check_docs.py", "--staged", str(repo.root)]) == 1
    assert "broken link" in capsys.readouterr().err
